-- Upload checks, configurable from the Rules screen. Built-in rules have kind = rule_key; custom rules use a
-- template kind (column_pattern, value_list, ...) whose params are validated in code.
CREATE TABLE upload_rules (
  id          CHAR(36)     NOT NULL,
  rule_key    VARCHAR(64)  NOT NULL,
  kind        VARCHAR(48)  NOT NULL,
  name        VARCHAR(120) NOT NULL,
  description VARCHAR(500) NOT NULL DEFAULT '',
  enabled     BOOLEAN      NOT NULL DEFAULT TRUE,
  locked      BOOLEAN      NOT NULL DEFAULT FALSE,
  params_json JSON         NOT NULL,
  sort_order  INT          NOT NULL DEFAULT 1000,
  created_by  CHAR(36)     NULL,
  updated_by  CHAR(36)     NULL,
  deleted_at  DATETIME(3)  NULL,
  created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY uq_upload_rules_key (rule_key),
  -- Money-safety rules can be tuned but never switched off or removed, whatever the app does.
  CONSTRAINT ck_upload_rules_locked_enabled CHECK (NOT locked OR enabled),
  CONSTRAINT ck_upload_rules_locked_kept CHECK (NOT locked OR deleted_at IS NULL),
  CONSTRAINT fk_upload_rules_created_by FOREIGN KEY (created_by) REFERENCES users (id),
  CONSTRAINT fk_upload_rules_updated_by FOREIGN KEY (updated_by) REFERENCES users (id)
);

CREATE TABLE upload_rule_changes (
  id          CHAR(36)    NOT NULL,
  rule_id     CHAR(36)    NOT NULL,
  changed_by  CHAR(36)    NOT NULL,
  action      ENUM('created','updated','enabled','disabled','deleted') NOT NULL,
  before_json JSON        NULL,
  after_json  JSON        NULL,
  created_at  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  KEY ix_upload_rule_changes_rule (rule_id, created_at),
  CONSTRAINT fk_upload_rule_changes_rule FOREIGN KEY (rule_id) REFERENCES upload_rules (id),
  CONSTRAINT fk_upload_rule_changes_user FOREIGN KEY (changed_by) REFERENCES users (id)
);

